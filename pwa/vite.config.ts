import preact from '@preact/preset-vite'
import { execSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { defineConfig } from 'vite'
import { VitePWA } from 'vite-plugin-pwa'
import pkg from './package.json' with { type: 'json' }
import { legalPages } from './vite/legal.ts'

// Ask git first: Workers Builds clones the repo, and the env var it was read from showed the
// branch name ("main") on the live build instead of a sha. Env vars only for builds without git.
function commit(): string {
  try { return execSync('git rev-parse --short HEAD').toString().trim() } catch { /* no git */ }
  return (process.env.WORKERS_CI_COMMIT_SHA ?? process.env.CF_PAGES_COMMIT_SHA ?? 'dev').slice(0, 7)
}

export default defineConfig({
  define: {
    __APP_VERSION__: JSON.stringify(`${pkg.version} · ${commit()}`),
  },
  // naice-notes.com: the landing page at /, the app at /app/, a branded 404. The legal pages are
  // generated by vite/legal.ts.
  build: {
    rolldownOptions: {
      input: {
        landing: fileURLToPath(new URL('./index.html', import.meta.url)),
        app: fileURLToPath(new URL('./app/index.html', import.meta.url)),
        notFound: fileURLToPath(new URL('./404.html', import.meta.url)),
      },
    },
  },
  plugins: [
    preact(),
    legalPages(fileURLToPath(new URL('../docs/legal', import.meta.url))),
    VitePWA({
      // A new deploy is fetched in the background and runs on the next app start —
      // nobody has to reinstall or clear anything.
      registerType: 'autoUpdate',
      includeAssets: ['favicon.png', 'apple-touch-icon.png'],
      manifest: {
        name: 'Naice Notes',
        short_name: 'Naice Notes',
        description: 'Shared notes and lists',
        lang: 'en',
        // The id stays '/' (what Chrome derived from the old start_url), so existing installs keep
        // their identity now that the app lives at /app/. The scope stays '/' so the landing page's
        // redirect for installed apps runs inside the app window.
        id: '/',
        start_url: '/app/',
        scope: '/',
        display: 'standalone',
        background_color: '#ffffff',
        theme_color: '#f0806a',
        icons: [
          { src: 'icon-192.png', sizes: '192x192', type: 'image/png' },
          { src: 'icon-512.png', sizes: '512x512', type: 'image/png' },
          { src: 'icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
        ],
      },
      workbox: {
        // Offline, any navigation under /app/ gets the app shell; / and the legal pages come from
        // the precache as their own files.
        navigateFallback: '/app/index.html',
        navigateFallbackAllowlist: [/^\/app(\/|$)/],
      },
    }),
  ],
})
